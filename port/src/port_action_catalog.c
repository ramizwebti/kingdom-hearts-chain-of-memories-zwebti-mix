unsigned PortActionCatalogCount(void) {return sizeof(sCatalog)/sizeof(sCatalog[0]);}
const PortActionCatalogEntry* PortActionCatalogGet(unsigned index) {
    return index<PortActionCatalogCount() ? &sCatalog[index] : NULL;
}
int PortActionCatalogFindNative(uint32_t move) {
    unsigned i;for(i=0;i<PortActionCatalogCount();++i) if(sCatalog[i].nativeMove==move) return (int)i;
    return -1;
}
const char* PortActionCatalogCategoryName(unsigned category) {
    static const char* const names[PORT_CATALOG_CATEGORY_COUNT]={"Techniques","Magic","Summons","Friends","Keyblades","Items"};
    return category<PORT_CATALOG_CATEGORY_COUNT ? names[category] : "";
}
unsigned PortActionCatalogCategoryCount(unsigned category) {
    unsigned i,n=0;for(i=0;i<PortActionCatalogCount();++i) n+=sCatalog[i].category==category;
    return n;
}
int PortActionCatalogValidMove(uint32_t move) {return PortActionCatalogFindNative(move)>=0;}
int PortActionCatalogCanUseAirborne(uint32_t move) {
    int i=PortActionCatalogFindNative(move);return i>=0 && !(sCatalog[i].flags&PORT_CATALOG_GROUND_ONLY);
}
int PortActionCatalogUsesEffectChannel(uint32_t move) {
    int i=PortActionCatalogFindNative(move);return i>=0 && (sCatalog[i].flags&PORT_CATALOG_EFFECT_CHANNEL)!=0;
}
unsigned PortActionCatalogFinisherCount(void) {
    unsigned i,n=0;for(i=0;i<PortActionCatalogCount();++i) n+=(sCatalog[i].flags&PORT_CATALOG_FINISHER)!=0;
    return n;
}
const PortActionCatalogEntry* PortActionCatalogGetFinisher(unsigned index) {
    unsigned i;for(i=0;i<PortActionCatalogCount();++i) if(sCatalog[i].flags&PORT_CATALOG_FINISHER) {
        if(!index--) return &sCatalog[i];
    }
    return NULL;
}
int PortActionCatalogFinisherEligible(uint32_t move) {
    int i=PortActionCatalogFindNative(move);return i>=0 && (sCatalog[i].flags&PORT_CATALOG_FINISHER)!=0;
}
